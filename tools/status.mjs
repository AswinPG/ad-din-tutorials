// Writes STATUS.md: where every video stands, per track and per language, plus open decisions.
// Usage: npm run status
import fs from "node:fs";
import path from "node:path";
import { loadSeries, ROOT, toMin, mmss, hours } from "./lib/catalog.mjs";

const { series, videos } = loadSeries();
const langs = series.languages.filter((l) => !l.source);
const inScope = videos.filter((v) => v.status !== "on-hold");
const count = (st) => inScope.filter((v) => v.status === st).length;
const mark = (v, code) => {
    const t = v.translations[code];
    if (!t) return "·";
    return t.status === "reviewed" ? "✓" : "draft";
};

let md = `# Status\n\nGenerated by \`npm run status\` on ${new Date().toISOString().slice(0, 10)}. Don't edit by hand; change the video files and re-run.\n\n`;
md += `**${inScope.length} videos in scope** (${videos.length - inScope.length} on hold) · target runtime ${hours(inScope.reduce((a, v) => a + toMin(v.target), 0))}\n\n`;
md += `| Status | Videos |\n|---|---|\n` + series.statuses.filter((s) => s !== "on-hold").map((s) => `| ${s} | ${count(s)} |`).join("\n") + `\n| on-hold | ${videos.length - inScope.length} |\n\n`;
md += `Translation columns: ✓ reviewed by a native speaker · draft · \`·\` not started.\n\n`;

for (const t of series.tracks) {
    const vs = videos.filter((v) => v.track === t.id);
    if (!vs.length) continue;
    md += `## Track ${t.id} · ${t.name}${t.status === "on-hold" ? " (on hold)" : ""}\n\n`;
    md += `| ID | Video | Status | Target | Scenes | EN narration | ${langs.map((l) => l.code).join(" | ")} | Flags |\n`;
    md += `|---|---|---|---|---|---|${langs.map(() => "---").join("|")}|---|\n`;
    for (const v of vs) {
        md += `| ${v.id} | [${v.title}](${v.file}) | ${v.status} | ${v.target} | ${v.scenes.length || "—"} | ${v.scenes.length ? mmss(v.narrationSecs / 60) : "—"} | ${langs.map((l) => mark(v, l.code)).join(" | ")} | ${v.flags.join("; ")} |\n`;
    }
    md += "\n";
}

const open = (series.decisions || []).filter((d) => d.status === "open");
md += `## Open decisions (${open.length})\n\nEdit these in \`series.yaml\` → \`decisions\`; set \`status: settled\` and add an \`outcome\` when decided.\n\n`;
md += open.map((d) => `- **${d.title}** ${d.detail} _(videos: ${d.videos})_`).join("\n") + "\n";

fs.writeFileSync(path.join(ROOT, "STATUS.md"), md);
console.log(`STATUS.md written · ${inScope.length} in scope · ${series.statuses.filter((s) => s !== "on-hold").map((s) => `${s} ${count(s)}`).join(" · ")}`);
